// Build src/digit-templates.js from labelled glyph clusters (see test-assets/README.md).
// usage: node tools/build-templates.mjs <scratchDir>
import fs from 'node:fs';
import { GLYPH_W, GLYPH_H } from '../src/weight-reader.js';
const dir = process.argv[2];
const glyphs = JSON.parse(fs.readFileSync(`${dir}/glyphs.json`));
const subA = JSON.parse(fs.readFileSync(`${dir}/sub_a.json`));
const subB = JSON.parse(fs.readFileSync(`${dir}/sub_b.json`));
const key = (g) => `${g.frame}:${g.pos}`;
const subOf = new Map([...subA.map((g) => [key(g), 'a' + g.sub]), ...subB.map((g) => [key(g), 'b' + g.sub])]);
// Labels assigned by visual inspection of the cluster sheets.
const LABELS = { 17: '0', 2: '1', 4: '2', 15: '2', 0: '3', 1: '4', 5: '5', 8: '5', 6: '7', a0: '6', b0: '8', b1: '8', b3: '9' };
const groups = {};
for (const g of glyphs) {
  const lab = LABELS[subOf.get(key(g)) ?? g.cluster];
  if (!lab) continue;
  (groups[lab] ||= []).push(g);
}
const templates = Object.keys(groups).sort().map((d) => {
  const m = groups[d], n = m.length;
  const vec = new Array(GLYPH_W * GLYPH_H).fill(0);
  let aspect = 0;
  for (const g of m) { g.vec.forEach((v, i) => (vec[i] += v / n)); aspect += g.aspect / n; }
  console.log(d, 'n=' + n, 'aspect=' + aspect.toFixed(3));
  return { digit: d, aspect: +aspect.toFixed(3), vec: vec.map((v) => +v.toFixed(2)) };
});
const body = `// Generated by tools/build-templates.mjs from the commissioning video
// (PXL_20261104_121605137.mp4). Glyphs are ${GLYPH_W}x${GLYPH_H} normalised ink.
export const GLYPH_W = ${GLYPH_W};
export const GLYPH_H = ${GLYPH_H};
export const DEFAULT_TEMPLATES = [
${templates.map((t) => `  { digit: '${t.digit}', aspect: ${t.aspect}, vec: [${t.vec.join(',')}] },`).join('\n')}
];
`;
fs.writeFileSync(new URL('../src/digit-templates.js', import.meta.url), body);
