// Build multi-condition digit templates from glyphs collected by eval-auto.mjs.
// Labels start as the current reader's best guess and are refined by
// re-classifying against the per-video means (a few rounds of self-training).
// The resulting templates MUST be checked by eye on the contact sheet.
// usage: node tools/self-train.mjs <outDir> glyphs1.json [glyphs2.json ...]
import fs from 'node:fs';
import { classifyGlyph, GLYPH_W, GLYPH_H } from '../src/weight-reader.js';
import { DEFAULT_TEMPLATES } from '../src/digit-templates.js';
import { writePGM } from './rawframes.mjs';

const [outDir, ...files] = process.argv.slice(2);
const sources = files.map((f) => ({ name: f.replace(/.*[\\/]/, '').replace('.json', ''), glyphs: JSON.parse(fs.readFileSync(f)) }));
const all = sources.flatMap((s) => s.glyphs.map((g) => ({ ...g, src: s.name })));
const LAST = ['0', '5'];

function means(glyphs, keyOf) {
  const groups = {};
  for (const g of glyphs) { const k = keyOf(g); if (k) (groups[k] ||= []).push(g); }
  return Object.entries(groups).filter(([, m]) => m.length >= 8).map(([k, m]) => {
    const vec = new Array(GLYPH_W * GLYPH_H).fill(0); let aspect = 0;
    for (const g of m) { g.vec.forEach((v, i) => (vec[i] += v / m.length)); aspect += g.aspect / m.length; }
    const [src, digit] = k.split('|');
    return { digit, src, n: m.length, aspect: +aspect.toFixed(3), vec: vec.map((v) => +v.toFixed(2)) };
  });
}

let templates = DEFAULT_TEMPLATES.map((t) => ({ ...t, src: 'default' }));
for (const g of all) g.lab = g.label;
for (let round = 0; round < 4; round++) {
  for (const g of all) {
    const ts = g.pos === -1 ? templates.filter((t) => LAST.includes(t.digit)) : templates;
    const r = classifyGlyph(g.vec, g.aspect, ts);
    g.lab = r.digit; g.sc = r.score; g.mg = r.margin;
  }
  // Only confident, unambiguous glyphs shape the next templates.
  const good = all.filter((g) => g.sc > 0.7 && g.mg > 0.1);
  templates = means(good, (g) => `${g.src}|${g.lab}`);
  const counts = {};
  for (const t of templates) counts[t.src] = (counts[t.src] || '') + `${t.digit}(${t.n}) `;
  console.log('round', round, 'good', good.length, '/', all.length);
  for (const [s, c] of Object.entries(counts)) console.log('  ', s, c);
}
fs.writeFileSync(`${outDir}/templates.json`, JSON.stringify(templates));

// Contact sheet: one row per digit; per source the template then 6 members.
const cell = 3, cw = GLYPH_W * cell + 2, ch = GLYPH_H * cell + 2, per = 7;
const cols = sources.length * per + sources.length;
const Wd = cw * cols, Hd = ch * 10;
const px = new Uint8Array(Wd * Hd).fill(40);
const put = (row, col, vec, bright = 255) => {
  for (let y = 0; y < GLYPH_H * cell; y++) for (let x = 0; x < GLYPH_W * cell; x++)
    px[(row * ch + y) * Wd + col * cw + x] = Math.round(bright * vec[Math.floor(y / cell) * GLYPH_W + Math.floor(x / cell)]);
};
sources.forEach((s, si) => {
  for (let d = 0; d < 10; d++) {
    const t = templates.find((t) => t.src === s.name && t.digit === String(d));
    const base = si * (per + 1);
    if (t) put(d, base, t.vec, 255);
    const mem = all.filter((g) => g.src === s.name && g.lab === String(d) && g.sc > 0.7 && g.mg > 0.1);
    const step = Math.max(1, Math.floor(mem.length / (per - 1)));
    for (let j = 0; j < per - 1 && j * step < mem.length; j++) put(d, base + 1 + j, mem[j * step].vec, 200);
  }
});
writePGM(`${outDir}/sheet.pgm`, Wd, Hd, px);

// Write src/digit-templates.js when asked.
if (process.env.WRITE_TEMPLATES) {
  const order = (a, b) => a.digit.localeCompare(b.digit) || a.src.localeCompare(b.src);
  const body = `// Generated by tools/self-train.mjs from the four phone videos
// (PXL_20261104_121605137/133247318/133641094/135221063.mp4), one template per
// digit per video (different distance, angle, glare and screen cleanliness).
// Glyphs are ${GLYPH_W}x${GLYPH_H} normalised ink. Checked by eye on the contact sheet.
export const GLYPH_W = ${GLYPH_W};
export const GLYPH_H = ${GLYPH_H};
export const DEFAULT_TEMPLATES = [
${templates.sort(order).map((t) => `  { digit: '${t.digit}', src: '${t.src}', aspect: ${t.aspect}, vec: [${t.vec.join(',')}] },`).join('\n')}
];
`;
  fs.writeFileSync(new URL('../src/digit-templates.js', import.meta.url), body);
  console.log('wrote', templates.length, 'templates');
}
